/**
 * Shared input validation for Supabase Edge Functions.
 *
 * Rules that apply to every function:
 *  - validate BEFORE spending money (Gemini calls) or writing to the database;
 *  - reject on the first violation, never "repair" the input;
 *  - never echo upstream error text, storage paths or keys back to the caller;
 *  - treat everything the model returns as untrusted until it is re-validated.
 *
 * This module is deliberately free of Deno APIs so it can be unit-tested with
 * the repository's Vitest suite (src/test/edgeValidation.test.ts).
 */

/** Hard ceiling on the JSON body, in bytes. Protects against large-payload abuse. */
export const MAX_BODY_BYTES = 8 * 1024;

/**
 * Panel identifiers are generated by the app (`src/data/dcs_panels.ts`) and are
 * lowercase slugs: `general-train`, `liquefaction-1`.
 */
export const PANEL_ID_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;

/**
 * Storage paths are constrained to safe characters, a known extension, and no
 * `..` segments — a caller must not be able to walk out of the bucket prefix.
 */
export const STORAGE_PATH_RE = /^(?!.*\.\.)[A-Za-z0-9][A-Za-z0-9 _./-]{0,199}\.(jpg|jpeg|png|webp)$/;

/**
 * Instrument tags as defined by ISA-5.1: function letters, an optional modifier,
 * a loop number and an optional suffix. Plant conventions add a unit prefix
 * (`X01-FT-501`) — allowed, but bounded.
 */
export const INSTRUMENT_TAG_RE = /^([A-Z0-9]{2,4}-)?[A-Z]{1,4}-?\d{1,6}[A-Z]{0,3}$/;

export const MAX_TAGS = 300;
export const MAX_TAG_LENGTH = 24;

/** Callers get a stable machine code plus a human hint; internals stay server-side. */
export interface ValidationError {
  code:
    | "BODY_TOO_LARGE"
    | "INVALID_JSON"
    | "MISSING_FIELD"
    | "INVALID_PANEL_ID"
    | "INVALID_STORAGE_PATH"
    | "INVALID_FORCE";
  hint: string;
}

export interface DetectRequest {
  panel_id: string;
  storage_path: string;
  force: boolean;
}

export type Validated<T> = { ok: true; value: T } | { ok: false; error: ValidationError };

/**
 * Type guard. Needed because the repository's tsconfig runs without
 * strictNullChecks, where a boolean discriminant does not narrow a union.
 */
export function isRejected<T>(result: Validated<T>): result is { ok: false; error: ValidationError } {
  return result.ok === false;
}

export function validateBodySize(byteLength: number): Validated<number> {
  if (!Number.isFinite(byteLength) || byteLength <= 0) {
    return { ok: false, error: { code: "INVALID_JSON", hint: "Empty request body." } };
  }
  if (byteLength > MAX_BODY_BYTES) {
    return {
      ok: false,
      error: { code: "BODY_TOO_LARGE", hint: `Request body must be ${MAX_BODY_BYTES} bytes or less.` },
    };
  }
  return { ok: true, value: byteLength };
}

export function validateDetectRequest(body: unknown): Validated<DetectRequest> {
  if (typeof body !== "object" || body === null || Array.isArray(body)) {
    return { ok: false, error: { code: "INVALID_JSON", hint: "Expected a JSON object." } };
  }
  const raw = body as Record<string, unknown>;
  const panelId = typeof raw.panel_id === "string" ? raw.panel_id.trim() : "";
  const storagePath = typeof raw.storage_path === "string" ? raw.storage_path.trim() : "";

  if (!panelId) return { ok: false, error: { code: "MISSING_FIELD", hint: "panel_id is required." } };
  if (!storagePath) return { ok: false, error: { code: "MISSING_FIELD", hint: "storage_path is required." } };
  if (!PANEL_ID_RE.test(panelId)) {
    return {
      ok: false,
      error: { code: "INVALID_PANEL_ID", hint: "panel_id must be a lowercase slug of up to 64 characters." },
    };
  }
  if (!STORAGE_PATH_RE.test(storagePath)) {
    return {
      ok: false,
      error: {
        code: "INVALID_STORAGE_PATH",
        hint: "storage_path must be a relative image path (jpg, jpeg, png or webp) with no '..' segments.",
      },
    };
  }
  if (raw.force !== undefined && typeof raw.force !== "boolean") {
    return { ok: false, error: { code: "INVALID_FORCE", hint: "force must be a boolean." } };
  }

  return { ok: true, value: { panel_id: panelId, storage_path: storagePath, force: raw.force === true } };
}

/**
 * The vision model's answer is data, not truth. Keep only strings that look like
 * instrument tags, cap the count, and drop anything else — otherwise a prompt
 * injection or a hallucination is written straight into the instrument register
 * that operators read.
 */
export function sanitiseDetectedTags(raw: unknown): string[] {
  if (!Array.isArray(raw)) return [];
  const out = new Set<string>();
  for (const entry of raw) {
    if (typeof entry !== "string") continue;
    const tag = entry.trim().toUpperCase().replace(/\s+/g, "");
    if (tag.length === 0 || tag.length > MAX_TAG_LENGTH) continue;
    if (!INSTRUMENT_TAG_RE.test(tag)) continue;
    out.add(tag);
    if (out.size >= MAX_TAGS) break;
  }
  return [...out];
}

/**
 * Map a validation error to the HTTP status the caller should see.
 * Kept separate from logging so the response never carries internal detail.
 */
export function statusForCode(code: ValidationError["code"]): number {
  switch (code) {
    case "BODY_TOO_LARGE":
      return 413;
    default:
      return 400;
  }
}
